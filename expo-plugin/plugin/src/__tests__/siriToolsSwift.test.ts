import fs from 'fs';
import path from 'path';

import { type ToolDeclaration, parseSiriTools } from '../siriTools/declaration';
import { SUPPORT_FILE, siriToolFiles, supportSwift, swiftString, toolSwift } from '../siriTools/swift';

const SAMPLE_DIR = path.join(__dirname, 'fixtures', 'siri-tools');
const SAMPLE_SOURCE = 'siri-tools.json';
const APP_NAME = 'Siri Spike';

const readSample = (name: string) => fs.readFileSync(path.join(SAMPLE_DIR, name), 'utf8');
const sample = () => parseSiriTools(JSON.parse(readSample(SAMPLE_SOURCE)), SAMPLE_SOURCE);

const ORDER_STATUS: ToolDeclaration = {
  name: 'GetOrderStatus',
  title: 'Get Order Status',
  description: 'Tells the person where an order is.',
  parameters: [{ name: 'orderNumber', type: 'string', title: 'Order Number' }],
  request: { method: 'GET', url: 'https://api.example.com/orders/{orderNumber}', body: [] },
  reply: 'Order {id} is {status}.',
};

describe('swiftString', () => {
  it.each([
    ['plain', '"plain"'],
    ['say "hi"', '"say \\"hi\\""'],
    ['back\\slash \\(not interpolated)', '"back\\\\slash \\\\(not interpolated)"'],
    ['two\nlines\tand tab\r', '"two\\nlines\\tand tab\\r"'],
  ])('quotes %j', (value, expected) => {
    expect(swiftString(value)).toBe(expected);
  });
});

describe('toolSwift', () => {
  it('generates a tool intent that calls the API and answers from the reply template', () => {
    expect(toolSwift(ORDER_STATUS)).toBe(`// Generated by expo-siri-ai-kit at prebuild. Edit your Siri tools declaration, not this file.
#if SIRI_AI_PREVIEW
import AppIntents
import Foundation
import SiriAIKit

@AppIntent(.tool)
struct GetOrderStatusIntent: AppIntent {
    static let title: LocalizedStringResource = "Get Order Status"
    static let description = IntentDescription("Tells the person where an order is.")

    @Parameter(title: "Order Number")
    var orderNumber: String

    func perform() async throws -> some IntentResult & ReturnsValue<String> & ProvidesDialog {
        let request = SiriToolsGenerated.Request(
            method: "GET",
            url: "https://api.example.com/orders/{orderNumber}",
            values: [
                "orderNumber": .string(orderNumber),
            ],
            body: [],
            auth: nil
        )
        let answer = await SiriToolsGenerated.tool.answer {
            try SiriToolsGenerated.reply("Order {id} is {status}.", from: try await request.send())
        }
        return .result(value: answer, dialog: "\\(answer)")
    }
}
#endif
`);
  });

  it('declares a tool without parameters with empty values', () => {
    const swift = toolSwift({
      ...ORDER_STATUS,
      parameters: [],
      request: { ...ORDER_STATUS.request, url: 'https://api.example.com/orders/latest' },
    });
    expect(swift).toContain('            values: [:],\n');
    expect(swift).not.toContain('@Parameter');
  });

  it.each([
    ['BookTrip', 'BookTripIntent.swift'],
    ['GetRecipes', 'GetRecipesIntent.swift'],
    ['SearchProducts', 'SearchProductsIntent.swift'],
  ])('generates %s from the sample declaration as approved', (name, expectedFile) => {
    const tool = sample().tools.find((candidate) => candidate.name === name)!;
    expect(toolSwift(tool)).toBe(readSample(expectedFile));
  });
});

describe('supportSwift', () => {
  it('generates the shared request and reply code as approved', () => {
    expect(supportSwift(APP_NAME)).toBe(readSample(SUPPORT_FILE));
  });

  it('quotes the app name', () => {
    expect(supportSwift('Bob\'s "Shop"')).toContain('static let tool = SiriTool(appName: "Bob\'s \\"Shop\\"")');
  });
});

describe('siriToolFiles', () => {
  it('writes the shared support file and one file per tool', () => {
    expect(siriToolFiles(sample(), APP_NAME).map((file) => file.fileName)).toEqual([
      SUPPORT_FILE,
      'SearchProductsIntent.swift',
      'GetRecipesIntent.swift',
      'BookTripIntent.swift',
    ]);
  });
});

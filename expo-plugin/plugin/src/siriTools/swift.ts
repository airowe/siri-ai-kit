import type { ScalarType, SiriToolsDeclaration, ToolDeclaration, ToolParameter } from './declaration';

export type GeneratedFile = { fileName: string; contents: string };

export const SUPPORT_FILE = 'SiriToolsGenerated.swift';

const HEADER = '// Generated by expo-syrup-ai-kit at prebuild. Edit your Siri tools declaration, not this file.';

const SWIFT_TYPES: Record<ScalarType, string> = {
  string: 'String',
  int: 'Int',
  double: 'Double',
  bool: 'Bool',
  date: 'Date',
};

/** A Swift string literal that reads exactly as `value`, with nothing interpolated. */
export function swiftString(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
  return `"${escaped}"`;
}

const upperFirst = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);
const intentName = (tool: ToolDeclaration) => `${tool.name}Intent`;
const enumName = (tool: ToolDeclaration, parameter: ToolParameter) => `${tool.name}${upperFirst(parameter.name)}`;

function swiftType(tool: ToolDeclaration, parameter: ToolParameter): string {
  return parameter.type === 'enum' ? enumName(tool, parameter) : SWIFT_TYPES[parameter.type];
}

/** How a parameter is handed to the request: enums by their raw value, everything else as itself. */
function requestValue(parameter: ToolParameter): string {
  return parameter.type === 'enum' ? `.string(${parameter.name}.rawValue)` : `.${parameter.type}(${parameter.name})`;
}

function parameterSwift(tool: ToolDeclaration, parameter: ToolParameter): string {
  const description = parameter.description === undefined ? '' : `, description: ${swiftString(parameter.description)}`;
  return `
    @Parameter(title: ${swiftString(parameter.title)}${description})
    var ${parameter.name}: ${swiftType(tool, parameter)}
`;
}

function valuesSwift(parameters: ToolParameter[]): string {
  if (parameters.length === 0) return '[:]';
  const entries = parameters.map((parameter) => `                ${swiftString(parameter.name)}: ${requestValue(parameter)},\n`);
  return `[\n${entries.join('')}            ]`;
}

function enumSwift(tool: ToolDeclaration, parameter: Extract<ToolParameter, { type: 'enum' }>): string {
  const name = enumName(tool, parameter);
  const cases = Object.keys(parameter.cases);
  const displays = Object.entries(parameter.cases).map(([key, title]) => `        .${key}: ${swiftString(title)},\n`);
  return `
enum ${name}: String, AppEnum {
${cases.map((key) => `    case ${key}\n`).join('')}
    static let typeDisplayRepresentation: TypeDisplayRepresentation = ${swiftString(parameter.title)}
    static let caseDisplayRepresentations: [${name}: DisplayRepresentation] = [
${displays.join('')}    ]
}
`;
}

/**
 * One tool intent: Siri fills the parameters, the intent calls the API, and the reply template becomes the answer.
 * A `dialog` tool has Siri speak the answer and end the turn; a `value` tool hands it to Siri, which can chain tools.
 */
export function toolSwift(tool: ToolDeclaration): string {
  const enums = tool.parameters.flatMap((parameter) => (parameter.type === 'enum' ? [enumSwift(tool, parameter)] : []));
  return `${HEADER}
#if SIRI_AI_PREVIEW
import AppIntents
import Foundation
import SyrupAIKit

@AppIntent(.tool)
struct ${intentName(tool)}: AppIntent {
    static let title: LocalizedStringResource = ${swiftString(tool.title)}
    static let description = IntentDescription(${swiftString(tool.description)})
${tool.parameters.map((parameter) => parameterSwift(tool, parameter)).join('')}
    func perform() async throws -> some IntentResult & ReturnsValue<String>${tool.returns === 'dialog' ? ' & ProvidesDialog' : ''} {
        let request = SiriToolsGenerated.Request(
            method: ${swiftString(tool.request.method)},
            url: ${swiftString(tool.request.url)},
            values: ${valuesSwift(tool.parameters)},
            body: [${tool.request.body.map(swiftString).join(', ')}]
        )
        let answer = await SiriToolsGenerated.tool.answer {
            try SiriToolsGenerated.reply(${swiftString(tool.reply)}, from: try await request.send())
        }
        return .result(value: answer${tool.returns === 'dialog' ? ', dialog: "\\(answer)"' : ''})
    }
}
${enums.join('')}#endif
`;
}

/** Code every generated tool shares: the `SiriTool`, the HTTP request and the reply template. */
export function supportSwift(appName: string): string {
  return `${HEADER}
#if SIRI_AI_PREVIEW
import Foundation
import SyrupAIKit

enum SiriToolsGenerated {
    static let tool = SiriTool(appName: ${swiftString(appName)})

    #if DEBUG || SIRI_AI_EVAL_SWITCHES
    /// An evaluation's negative control turns this on at launch: every generated tool then calls a host that never
    /// resolves, so Siri must say it couldn't reach the app. Builds without either condition, such as an App Store
    /// archive, don't read it.
    static let badHost: EvalSwitch = "bad-host"
    static let unreachableURL = URL(string: "https://siri-ai-eval-bad-host.invalid")!
    #endif

    /// A parameter value as Siri filled it in.
    enum Value: Sendable {
        case string(String)
        case int(Int)
        case double(Double)
        case bool(Bool)
        case date(Date)

        /// How the value reads in a URL.
        var text: String {
            switch self {
            case .string(let value): value
            case .int(let value): String(value)
            case .double(let value): String(value)
            case .bool(let value): value ? "true" : "false"
            case .date(let value): value.formatted(.iso8601)
            }
        }

        /// How the value reads in a JSON body.
        var json: Any {
            switch self {
            case .string(let value): value
            case .int(let value): value
            case .double(let value): value
            case .bool(let value): value
            case .date(let value): value.formatted(.iso8601)
            }
        }
    }

    struct Request: Sendable {
        let method: String
        let url: String
        let values: [String: Value]
        let body: [String]

        /// The decoded JSON response. Any non-2xx status fails.
        func send() async throws -> Any {
            var request = URLRequest(url: try resolvedURL())
            request.httpMethod = method
            if !body.isEmpty {
                let fields = body.compactMap { name in values[name].map { (name, $0.json) } }
                request.httpBody = try JSONSerialization.data(withJSONObject: Dictionary(uniqueKeysWithValues: fields))
                request.setValue("application/json", forHTTPHeaderField: "Content-Type")
            }
            let (data, response) = try await URLSession.shared.data(for: request)
            let status = (response as? HTTPURLResponse)?.statusCode ?? 0
            guard (200..<300).contains(status) else { throw ToolFailure.failed }
            return try JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed])
        }

        func resolvedURL() throws -> URL {
            #if DEBUG || SIRI_AI_EVAL_SWITCHES
            if SiriToolsGenerated.badHost.isOn() { return SiriToolsGenerated.unreachableURL }
            #endif
            var text = url
            for (name, value) in values {
                let encoded = value.text.addingPercentEncoding(withAllowedCharacters: .siriToolValueAllowed) ?? value.text
                text = text.replacingOccurrences(of: "{\\(name)}", with: encoded)
            }
            guard let resolved = URL(string: text) else { throw ToolFailure.failed }
            return resolved
        }
    }

    /// Fills \`{path.to.field}\` placeholders from a JSON response. A name on an array maps over its elements,
    /// a number indexes it, \`count\` is its length, and an array reads as a comma-separated list.
    static func reply(_ template: String, from json: Any) throws -> String {
        var result = ""
        var rest = Substring(template)
        while let open = rest.firstIndex(of: "{"), let close = rest[open...].firstIndex(of: "}") {
            result += rest[..<open]
            let path = rest[rest.index(after: open)..<close].split(separator: ".").map(String.init)
            guard let value = lookup(path, in: json) else { throw ToolFailure.failed }
            result += speak(value)
            rest = rest[rest.index(after: close)...]
        }
        return result + rest
    }

    static func lookup(_ path: [String], in json: Any) -> Any? {
        guard let key = path.first else { return json }
        let rest = Array(path.dropFirst())
        if let array = json as? [Any] {
            if key == "count" { return lookup(rest, in: array.count) }
            if let index = Int(key) { return array.indices.contains(index) ? lookup(rest, in: array[index]) : nil }
            let values = array.compactMap { lookup(path, in: $0) }
            return values.count == array.count ? values : nil
        }
        guard let object = json as? [String: Any], let value = object[key], !(value is NSNull) else { return nil }
        return lookup(rest, in: value)
    }

    static func speak(_ value: Any) -> String {
        switch value {
        case let array as [Any]: array.map(speak).joined(separator: ", ")
        case let number as NSNumber where CFGetTypeID(number) == CFBooleanGetTypeID(): number.boolValue ? "yes" : "no"
        case let number as NSNumber: number.doubleValue.formatted(.number.precision(.fractionLength(0...2)).grouping(.never))
        default: "\\(value)"
        }
    }

}

private extension CharacterSet {
    /// Query-safe characters minus the ones that would split a path segment or a query value.
    static let siriToolValueAllowed = CharacterSet.urlQueryAllowed.subtracting(CharacterSet(charactersIn: "&+=?/#"))
}
#endif
`;
}

/** The shared support file, then one file per tool, in declaration order. */
export function siriToolFiles(declaration: SiriToolsDeclaration, appName: string): GeneratedFile[] {
  return [
    { fileName: SUPPORT_FILE, contents: supportSwift(appName) },
    ...declaration.tools.map((tool) => ({ fileName: `${intentName(tool)}.swift`, contents: toolSwift(tool) })),
  ];
}
